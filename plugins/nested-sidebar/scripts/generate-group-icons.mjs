#!/usr/bin/env node
/**
 * Writes `assets/group-icons.txt`: the artwork for every icon the group picker
 * offers, as JSON, keyed by Hugeicons export name.
 *
 * Why this file exists at all. `@hugeicons/core-free-icons/loader` resolves an
 * icon through a static import map — one `() => import('./XxxIcon.js')` per
 * icon, six thousand of them. A plugin frontend is a single bundle with code
 * splitting off, so every one of those imports was inlined: the loader dragged
 * 6.1 MB of icon artwork into `dist/app.js`, which bb then loaded on the
 * deferred plugin boot pass of every window. The artwork is not needed to draw
 * the sidebar; it is needed when the user opens the picker.
 *
 * Why a generated source file. The plugin server cannot open a file — bb builds
 * that bundle with a browser-ish resolver, so a `node:` import is a build error
 * — and a path install is worse still: bb imports `server.ts` itself, so
 * whatever this is must be importable by plain Node. That leaves one generated
 * JavaScript module, which both bb's bundler and Node can load.
 *
 * Why the artwork is a string and not an object literal. A 6 MB object literal
 * costs about 120 ms of parse on every plugin load; a string literal costs a
 * scan, and the `JSON.parse` waits for the first icon actually asked for. The
 * hand-written `.d.ts` beside this file keeps that 6 MB out of `tsc`'s way.
 *
 * The icon set is exactly `GROUP_ICON_OPTIONS`, so this file can never drift
 * from the names the picker offers and the names stored rows are validated
 * against.
 *
 * Usage: `node scripts/generate-group-icons.mjs [--force]`.
 * Without `--force` it does nothing when the output is newer than the name list.
 */
import { stat, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const namesSource = join(root, "lib", "group-icons.ts");
const output = join(root, "lib", "group-icons-data.js");

const force = process.argv.includes("--force");

async function isUpToDate() {
  try {
    const [source, written] = await Promise.all([
      stat(namesSource),
      stat(output),
    ]);
    return written.mtimeMs >= source.mtimeMs;
  } catch {
    return false;
  }
}

if (!force && (await isUpToDate())) {
  console.log("group-icons-data.js is up to date; pass --force to rebuild it.");
  process.exit(0);
}

const { GROUP_ICON_OPTIONS } = await import(namesSource);

const icons = {};
const startedAt = Date.now();
for (const name of GROUP_ICON_OPTIONS) {
  const module = await import(`@hugeicons/core-free-icons/${name}`);
  icons[name] = module.default;
}

const json = JSON.stringify({ version: 1, icons });
await writeFile(
  output,
  [
    "// GENERATED by scripts/generate-group-icons.mjs — do not edit.",
    "//",
    "// The group picker's artwork as JSON text, one line, kept out of the",
    "// frontend bundle and out of `tsc`'s parse of this project.",
    `export const GROUP_ICON_ARTWORK_JSON = ${JSON.stringify(json)};`,
    "",
  ].join("\n"),
);

console.log(
  `${GROUP_ICON_OPTIONS.length} icons in ${Date.now() - startedAt}ms -> ` +
    `${(json.length / 1048576).toFixed(2)} MB of JSON`
);
